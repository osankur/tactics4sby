# Summary rendering (for logs and the CLI)
# --------------------------------------------------------------------------- #


def _describe_tactic(tactic: Tactic, lines: list[str], indent: int) -> None:
    """Append an indented rendering of ``tactic`` (and its sub-tactics)."""
    pad = "  " * indent
    if isinstance(tactic, AssumeGuaranteeTactic):
        lines.append(f"{pad}tactic: {tactic.name}")
        if tactic.auto:
            lines.append(f"{pad}  auto: true")
            if tactic.instances is not None:
                lines.append(f"{pad}  instances: {[i.name for i in tactic.instances]}")
            if tactic.inline:
                lines.append(f"{pad}  inline: {list(tactic.inline)}")
        else:
            lines.append(f"{pad}  auto: false (manual order)")
            lines.append(
                f"{pad}  instances: {[i.name for i in tactic.instances or ()]}"
            )
        if tactic.instances is not None:
            for instance in tactic.instances:
                if instance.tactic is not None:
                    lines.append(f"{pad}  instance {instance.name!r}:")
                    _describe_tactic(instance.tactic, lines, indent + 2)
        if tactic.tactic is not None:
            lines.append(f"{pad}  main VC:")
            _describe_tactic(tactic.tactic, lines, indent + 2)
    elif isinstance(tactic, CutpointTactic):
        lines.append(f"{pad}tactic: cutpoint on {tactic.selection}")
        if tactic.tactic is not None:
            _describe_tactic(tactic.tactic, lines, indent + 1)
    elif isinstance(tactic, SplitTactic):
        lines.append(f"{pad}tactic: split on {tactic.split_wire}")
        for label, case in (
            ("case_false", tactic.case_false),
            ("case_true", tactic.case_true),
        ):
            if case is None:
                lines.append(f"{pad}  {label}: prove directly")
            else:
                lines.append(f"{pad}  {label}:")
                _describe_tactic(case, lines, indent + 2)
    elif isinstance(tactic, NoneTactic):
        lines.append(f"{pad}tactic: none")


def _describe_goal(
    goal: Goal, strategy: ProofStrategy, lines: list[str], indent: int
) -> None:
    """Append an indented rendering of ``goal`` (and its tactic)."""
    pad = "  " * indent
    flags: list[str] = []
    if strategy.early_assume:
        flags.append("early-assume")
    if strategy.early_assert:
        flags.append("early-assert")
    suffix = f" [{', '.join(flags)}]" if flags else ""
    label = f"{goal.name!r} " if goal.name else ""
    lines.append(f"{pad}- {label}module={goal.module}{suffix}")
    if goal.tactic is not None:
        _describe_tactic(goal.tactic, lines, indent + 1)
    else:
        lines.append(f"{pad}  tactic: none (prove directly)")


def summarize(strategy: ProofStrategy) -> str:
    """A short human readable rendering of ``strategy``, for logs and the CLI."""
    lines: list[str] = []
    lines.append(f"header ({len(strategy.header)} command(s)):")
    lines.extend(f"  {command}" for command in strategy.header)
    lines.append(f"top: {strategy.top}")
    lines.append("goal:")
    _describe_goal(strategy.goal, strategy, lines, 1)
    lines.append(f"subgoals ({len(strategy.subgoals)}):")
    for goal in strategy.subgoals:
        _describe_goal(goal, strategy, lines, 1)
    return "\n".join(lines)
