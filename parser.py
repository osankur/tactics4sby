"""Data model and parser for proof strategy JSON files."""

from __future__ import annotations

import json
from dataclasses import dataclass, field
from pathlib import Path
from typing import Any, ClassVar, NoReturn

__all__ = [
    "ProofStrategyError",
    "Tactic",
    "AssumeGuaranteeTactic",
    "InductiveAssumeGuaranteeTactic",
    "CutpointTactic",
    "SplitTactic",
    "Instance",
    "Objective",
    "ProofStrategy",
    "parse_file",
    "parse_string",
    "parse_dict",
]


class ProofStrategyError(ValueError):
    """A proof strategy file is malformed.

    The message is prefixed with the JSON path of the offending value.
    """


TACTIC_NAMES: tuple[str, ...] = (
    "assume_guarantee",
    "inductive_assume_guarantee",
    "cutpoint",
    "split",
)

#: Default sby options and engines, inherited when neither the node nor any of
#: its ancestors specifies them.
DEFAULT_OPTIONS: tuple[str, ...] = ("mode prove",)
DEFAULT_ENGINES: tuple[str, ...] = ("smtbmc",)


# --------------------------------------------------------------------------- #
# Data model
# --------------------------------------------------------------------------- #


@dataclass(frozen=True)
class Tactic:
    """Base class for the tactics an objective or VC can be decomposed with.

    ``name`` is the string that selects this tactic in the JSON file.
    ``json_path`` records where this object was parsed from and is excluded
    from comparison/hashing.

    ``options`` and ``engines`` are the sby options and engines to use for the
    verification conditions generated by this tactic.  They are inherited
    hereditarily: a node that does not specify them takes the values of the
    closest ancestor that does, falling back to :data:`DEFAULT_OPTIONS` /
    :data:`DEFAULT_ENGINES`.  The parser resolves the inheritance, so the
    values stored here are always the effective ones.
    """

    options: tuple[str, ...] = DEFAULT_OPTIONS
    engines: tuple[str, ...] = DEFAULT_ENGINES
    json_path: str = field(default="", compare=False)


@dataclass(frozen=True, kw_only=True)
class Instance:
    """A module instance taking part in an assume-guarantee decomposition.

    ``name`` is the name of the instance cell.  ``tactic``, when given, is the
    tactic used to prove the verification condition for this particular
    instance; ``None`` means the instance's VC is proven directly.
    """

    name: str
    tactic: Tactic | None = None
    json_path: str = field(default="", compare=False)


@dataclass(frozen=True, kw_only=True)
class AssumeGuaranteeTactic(Tactic):
    """Acyclic assume-guarantee decomposition.

    ``auto`` selects how the instances are ordered.  When true (the default)
    the order is computed automatically, ``instances`` (if given) restricts
    which instances take part, and ``inline`` names the instances to inline.
    When false ``instances`` gives the order explicitly and every instance not
    listed is inlined.

    ``instances`` is ``None`` when the field is absent.  In manual mode
    (``auto`` false) it is required, so it is never ``None`` there.

    ``tactic``, when given, is the tactic used to prove the main verification
    condition of this objective.
    """

    auto: bool = True
    instances: tuple[Instance, ...] | None = None
    inline: tuple[str, ...] = ()
    tactic: Tactic | None = None

    name: ClassVar[str] = "assume_guarantee"


@dataclass(frozen=True, kw_only=True)
class InductiveAssumeGuaranteeTactic(AssumeGuaranteeTactic):
    """Assume-guarantee decomposition for apparently circular reasoning.

    Structurally identical to :class:`AssumeGuaranteeTactic`.  The assumptions
    of each instance are proven at time ``t`` assuming the assertions of the
    other modules up to time ``t-1``.
    """

    name: ClassVar[str] = "inductive_assume_guarantee"


@dataclass(frozen=True, kw_only=True)
class CutpointTactic(Tactic):
    """Apply ``cutpoint`` to a wire, implementing a user-defined abstraction.

    ``wire`` is a Yosys select expression referring to the top module's wires.
    ``tactic``, when given, is applied after the cutpoint.
    """

    wire: str
    tactic: Tactic | None = None

    name: ClassVar[str] = "cutpoint"


@dataclass(frozen=True, kw_only=True)
class SplitTactic(Tactic):
    """Case split on a Verilog expression.

    ``case_false`` / ``case_true`` are the tactics applied to the branch where
    ``split_expression`` is false / true; ``None`` means that branch is proven
    directly.  The expression is evaluated in the module owning the VC.

    ``tactic``, when given, is applied after the split (e.g. to the whole
    verification condition once both cases have been discharged).
    """

    split_expression: str
    case_false: Tactic | None = None
    case_true: Tactic | None = None
    tactic: Tactic | None = None

    name: ClassVar[str] = "split"


@dataclass(frozen=True, kw_only=True)
class Objective:
    """A single verification objective.

    ``name`` is an optional user-supplied label identifying the objective (for
    logs and error messages); it has no semantic effect.

    The contract of the objective's ``top`` module is *all* of its assertions
    and assumptions; there is no way to select a subset.  ``tactic`` is
    ``None`` for a leaf objective, proven directly.


    ``options`` / ``engines`` are inherited hereditarily like on tactics; the
    parser stores the effective values.
    """

    top: str
    name: str | None = None
    early_assume: bool = False
    early_assert: bool = False
    tactic: Tactic | None = None
    options: tuple[str, ...] = DEFAULT_OPTIONS
    engines: tuple[str, ...] = DEFAULT_ENGINES
    json_path: str = field(default="", compare=False)


@dataclass(frozen=True, kw_only=True)
class ProofStrategy:
    """A parsed proof strategy: the top-level document.

    ``header`` lists the Yosys commands run once, in order, before any
    objective.  ``files`` is a tuple of source files to be considered in the sby configuration scripts.
    ``source`` records where the strategy was read from and is excluded from comparison/hashing.
    """

    header: tuple[str, ...]
    files: tuple[str, ...]
    objectives: tuple[Objective, ...]
    source: Path | None = field(default=None, compare=False)
    json_path: str = field(default="", compare=False)
    multiclock: bool = False

    # TODO The following four fields are new
    early_assume: bool = False
    early_assert: bool = False
    script: tuple[str, ...] = field(default_factory=lambda: tuple())
    options: tuple[str, ...] = DEFAULT_OPTIONS
    engines: tuple[str, ...] = DEFAULT_ENGINES


# --------------------------------------------------------------------------- #
# Parser
# --------------------------------------------------------------------------- #

_OBJECTIVE_REQUIRED = ("top",)
_OBJECTIVE_OPTIONAL = (
    "name",
    "early-assume",
    "early-assert",
    "tactic",
    "options",
    "engines",
)
#: Nested objectives (reached through a tactic) may not set the early flags:
#: they are inherited from the top-level objective.
_NESTED_OBJECTIVE_OPTIONAL = ("name", "tactic", "options", "engines")
_PROOF_STRATEGY_REQUIRED = ("header", "files", "objectives")
_PROOF_STRATEGY_OPTIONAL = ()
_TOP_REQUIRED = ("proof_strategy",)
_TOP_OPTIONAL = ("$schema",)

#: Keys every tactic tolerates in addition to its own.
_TACTIC_COMMON_OPTIONAL = ("options", "engines")

#: Per tactic name: the keys it requires, and the keys it additionally tolerates.
#: 'name' is required by every tactic and is listed in the required tuple.
_TACTIC_KEYS: dict[str, tuple[tuple[str, ...], tuple[str, ...]]] = {
    "assume_guarantee": (
        ("name",),
        ("auto", "instances", "inline", "tactic") + _TACTIC_COMMON_OPTIONAL,
    ),
    "inductive_assume_guarantee": (
        ("name",),
        ("auto", "instances", "inline", "tactic") + _TACTIC_COMMON_OPTIONAL,
    ),
    "cutpoint": (("name", "wire"), ("tactic",) + _TACTIC_COMMON_OPTIONAL),
    "split": (
        ("name", "split_expression"),
        ("case_false", "case_true", "tactic") + _TACTIC_COMMON_OPTIONAL,
    ),
}


class _Parser:
    """Recursive-descent parser for proof strategy documents.

    Every error message is prefixed with the JSON path of the offending value.
    """

    # -- helpers ----------------------------------------------------------- #

    def _err(self, path: str, message: str) -> NoReturn:
        raise ProofStrategyError(f"{path}: {message}")

    def _object(self, value: Any, path: str) -> dict[str, Any]:
        if not isinstance(value, dict):
            self._err(path, f"expected an object, got {type(value)}")
        return value

    def _check_keys(
        self,
        obj: dict[str, Any],
        path: str,
        required: tuple[str, ...],
        optional: tuple[str, ...],
    ) -> None:
        unknown = sorted(set(obj) - set(required) - set(optional))
        if unknown:
            allowed = sorted(set(required) | set(optional))
            self._err(
                path,
                "unknown key(s): "
                + ", ".join(f"'{key}'" for key in unknown)
                + "; allowed: "
                + ", ".join(f"'{key}'" for key in allowed),
            )
        missing = [key for key in required if key not in obj]
        if missing:
            self._err(
                path,
                "missing required key(s): " + ", ".join(f"'{key}'" for key in missing),
            )

    def _string(self, value: Any, path: str, *, allow_empty: bool = False) -> str:
        if not isinstance(value, str):
            self._err(path, f"expected a string, got {type(value)}")
        if not allow_empty and not value.strip():
            self._err(path, "must not be empty")
        return value

    def _bool(self, value: Any, path: str) -> bool:
        if not isinstance(value, bool):
            self._err(path, f"expected a boolean, got {type(value)}")
        return value

    def _string_list(
        self, value: Any, path: str, *, allow_empty: bool = True
    ) -> tuple[str, ...]:
        if not isinstance(value, list):
            self._err(path, f"expected an array of strings, got {type(value)}")
        items = tuple(
            self._string(item, f"{path}[{index}]") for index, item in enumerate(value)
        )
        if not allow_empty and not items:
            self._err(path, "must not be an empty array")
        return items

    def _check_distinct(self, names: list[str], path: str, what: str) -> None:
        seen: set[str] = set()
        for name in names:
            if name in seen:
                self._err(path, f"duplicate {what} name {name!r}")
            seen.add(name)

    # -- grammar ----------------------------------------------------------- #

    def top_level_objective(self, value: Any, path: str) -> Objective:
        """Parse an objective from ``proof_strategy.objectives``.

        Only these objectives may set ``early-assume`` / ``early-assert``;
        the values are then inherited by every nested objective below them.
        """
        obj = self._object(value, path)
        self._check_keys(obj, path, _OBJECTIVE_REQUIRED, _OBJECTIVE_OPTIONAL)

        early_assume = (
            self._bool(obj["early-assume"], f"{path}.early-assume")
            if "early-assume" in obj
            else False
        )
        early_assert = (
            self._bool(obj["early-assert"], f"{path}.early-assert")
            if "early-assert" in obj
            else False
        )
        if early_assume and not early_assert:
            self._err(path, "'early-assume' requires 'early-assert' to be true")

        return self._objective_body(
            obj, path, early_assume=early_assume, early_assert=early_assert
        )

    def _objective_body(
        self,
        obj: dict[str, Any],
        path: str,
        *,
        early_assume: bool,
        early_assert: bool,
    ) -> Objective:
        top = self._string(obj["top"], f"{path}.top")
        name = (
            self._string(obj["name"], f"{path}.name")
            if obj.get("name") is not None
            else None
        )
        options = self._inherited_string_list(obj, "options", path, DEFAULT_OPTIONS)
        engines = self._inherited_string_list(obj, "engines", path, DEFAULT_ENGINES)

        tactic: Tactic | None = None
        if obj.get("tactic") is not None:
            tactic = self.tactic(
                obj["tactic"],
                f"{path}.tactic",
                options=options,
                engines=engines,
            )

        return Objective(
            top=top,
            name=name,
            early_assume=early_assume,
            early_assert=early_assert,
            tactic=tactic,
            options=options,
            engines=engines,
            json_path=path,
        )

    def _inherited_string_list(
        self,
        obj: dict[str, Any],
        key: str,
        path: str,
        inherited: tuple[str, ...],
    ) -> tuple[str, ...]:
        """Read ``key`` from ``obj`` if present, else return ``inherited``.

        ``options`` and ``engines`` are inherited hereditarily; the parser
        resolves the inheritance so every node stores its effective values.
        """
        if obj.get(key) is None:
            return inherited
        return self._string_list(obj[key], f"{path}.{key}")

    def tactic(
        self,
        value: Any,
        path: str,
        *,
        options: tuple[str, ...] = DEFAULT_OPTIONS,
        engines: tuple[str, ...] = DEFAULT_ENGINES,
    ) -> Tactic:
        obj = self._object(value, path)
        if "name" not in obj:
            self._err(path, "missing required key: 'name'")
        name = self._string(obj["name"], f"{path}.name")
        if name not in _TACTIC_KEYS:
            self._err(
                f"{path}.name",
                f"unknown tactic {name!r}; expected one of "
                + ", ".join(repr(known) for known in TACTIC_NAMES),
            )
        required, optional = _TACTIC_KEYS[name]
        self._check_keys(obj, path, required, optional)

        options = self._inherited_string_list(obj, "options", path, options)
        engines = self._inherited_string_list(obj, "engines", path, engines)
        common = {"options": options, "engines": engines}

        if name in ("assume_guarantee", "inductive_assume_guarantee"):
            return self._assume_guarantee(obj, path, name=name, **common)

        if name == "cutpoint":
            wire = self._string(obj["wire"], f"{path}.wire")
            tactic = self._optional_tactic(obj, "tactic", path, **common)
            return CutpointTactic(
                wire=wire,
                tactic=tactic,
                options=options,
                engines=engines,
                json_path=path,
            )

        # name == "split"
        expression = self._string(obj["split_expression"], f"{path}.split_expression")
        case_false = self._optional_case(obj, "case_false", path, **common)
        case_true = self._optional_case(obj, "case_true", path, **common)
        tactic = self._optional_tactic(obj, "tactic", path, **common)
        return SplitTactic(
            split_expression=expression,
            case_false=case_false,
            case_true=case_true,
            tactic=tactic,
            options=options,
            engines=engines,
            json_path=path,
        )

    def _optional_tactic(
        self,
        obj: dict[str, Any],
        key: str,
        path: str,
        **common: Any,
    ) -> Tactic | None:
        """An optional nested tactic: absent means "prove directly"."""
        if obj.get(key) is None:
            return None
        value = obj[key]
        if isinstance(value, dict) and not value:
            self._err(
                f"{path}.{key}",
                "an empty object is not a tactic: omit the field to prove "
                "this case directly",
            )
        return self.tactic(value, f"{path}.{key}", **common)

    def _optional_case(
        self,
        obj: dict[str, Any],
        key: str,
        path: str,
        **common: Any,
    ) -> Tactic | None:
        """A split case is either absent (prove directly) or a tactic object."""
        return self._optional_tactic(obj, key, path, **common)

    def _assume_guarantee(
        self,
        obj: dict[str, Any],
        path: str,
        *,
        name: str,
        options: tuple[str, ...],
        engines: tuple[str, ...],
    ) -> AssumeGuaranteeTactic:
        common = {"options": options, "engines": engines}

        auto = self._bool(obj["auto"], f"{path}.auto") if "auto" in obj else True

        instances: tuple[Instance, ...] | None = None
        if obj.get("instances") is not None:
            instances = self._instance_list(
                obj["instances"], f"{path}.instances", **common
            )
            self._check_distinct(
                [instance.name for instance in instances],
                f"{path}.instances",
                "instance",
            )
        elif not auto:
            self._err(
                path,
                "'instances' is required when 'auto' is false: it gives the "
                "order in which the instances are considered",
            )

        inline: tuple[str, ...] = ()
        if obj.get("inline") is not None:
            if not auto:
                self._err(
                    f"{path}.inline",
                    "'inline' is only allowed when 'auto' is true; in manual "
                    "mode every instance not listed in 'instances' is inlined",
                )
            inline = self._string_list(obj["inline"], f"{path}.inline")
            self._check_distinct(list(inline), f"{path}.inline", "inline instance")

        if inline and instances:
            raise ProofStrategyError(
                f"{path}: 'inline' and 'instances' are mutually exclusive"
            )

        tactic = self._optional_tactic(obj, "tactic", path, **common)

        cls = (
            InductiveAssumeGuaranteeTactic
            if name == "inductive_assume_guarantee"
            else AssumeGuaranteeTactic
        )
        return cls(
            auto=auto,
            instances=instances,
            inline=inline,
            tactic=tactic,
            options=options,
            engines=engines,
            json_path=path,
        )

    def _instance_list(
        self,
        value: Any,
        path: str,
        **common: Any,
    ) -> tuple[Instance, ...]:
        """The ``instances`` list: each entry names an instance cell and may
        carry a tactic used to prove that instance's verification condition."""
        items = self._require_nonempty_list(value, path)
        instances: list[Instance] = []
        for index, item in enumerate(items):
            entry_path = f"{path}[{index}]"
            entry = self._object(item, entry_path)
            self._check_keys(entry, entry_path, ("name",), ("tactic",))
            instance_name = self._string(entry["name"], f"{entry_path}.name")
            tactic = self._optional_tactic(entry, "tactic", entry_path, **common)
            instances.append(
                Instance(name=instance_name, tactic=tactic, json_path=entry_path)
            )
        return tuple(instances)

    def _require_nonempty_list(self, value: Any, path: str) -> list[Any]:
        if not isinstance(value, list):
            self._err(path, f"expected an array, got {type(value)}")
        if not value:
            self._err(path, "must not be an empty array")
        return value

    def document(self, value: Any, source: Path | None) -> ProofStrategy:
        root = self._object(value, "<root>")
        self._check_keys(root, "<root>", _TOP_REQUIRED, _TOP_OPTIONAL)

        ps = self._object(root["proof_strategy"], "proof_strategy")
        self._check_keys(
            ps, "proof_strategy", _PROOF_STRATEGY_REQUIRED, _PROOF_STRATEGY_OPTIONAL
        )
        header = self._string_list(ps["header"], "proof_strategy.header")
        files = self._string_list(ps["files"], "proof_strategy.files")
        if not isinstance(ps["objectives"], list):
            self._err(
                "proof_strategy.objectives",
                f"expected an array of objectives, got {type(ps['objectives'])}",
            )
        objectives = tuple(
            self.top_level_objective(item, f"proof_strategy.objectives[{index}]")
            for index, item in enumerate(ps["objectives"])
        )
        return ProofStrategy(
            header=header,
            files=files,
            objectives=objectives,
            source=source,
            json_path="proof_strategy",
        )


